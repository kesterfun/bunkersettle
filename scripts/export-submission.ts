import * as fs from "fs";
import * as path from "path";

const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.join(ROOT, "submission");
const MANIFEST_NAME = "MANIFEST.txt";

const EXCLUDED_DIRS = new Set([
  "node_modules",
  "dist",
  "artifacts",
  "cache",
  "coverage",
  "typechain-types",
]);
const EXCLUDED_FILES = new Set([".env", "deployments.json"]);

interface ExportedFile {
  original: string;
  exported: string;
}

const exported: ExportedFile[] = [];
const warnings: string[] = [];

// Walks a repo-relative directory recursively and returns repo-relative posix paths.
function walk(relDir: string, out: string[] = []): string[] {
  const absDir = path.join(ROOT, relDir);
  for (const dirent of fs.readdirSync(absDir, { withFileTypes: true })) {
    const rel = path.posix.join(relDir, dirent.name);
    if (dirent.isDirectory()) {
      if (!EXCLUDED_DIRS.has(dirent.name)) {
        walk(rel, out);
      }
    } else if (dirent.isFile() && !EXCLUDED_FILES.has(dirent.name)) {
      out.push(rel);
    }
  }
  return out;
}

function copyFile(original: string, target: string): void {
  const dst = path.join(OUT_DIR, target);
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.copyFileSync(path.join(ROOT, original), dst);
  exported.push({ original, exported: target });
}

// Copies a file that must exist; a missing one aborts the export.
function copyRequired(rel: string): void {
  if (!fs.existsSync(path.join(ROOT, rel))) {
    throw new Error(`Required file missing: ${rel}`);
  }
  copyFile(rel, rel);
}

// Copies a file that may not exist yet; a missing one only produces a warning.
function copyOptional(rel: string): void {
  if (!fs.existsSync(path.join(ROOT, rel))) {
    warnings.push(`Optional file not found, skipped: ${rel}`);
    return;
  }
  copyFile(rel, rel);
}

function exportContracts(): void {
  const sources = walk("contracts").filter((f) => f.endsWith(".sol"));
  for (const rel of sources) {
    const target = rel.slice(0, -".sol".length) + ".txt";
    copyFile(rel, target);
  }
}

function exportTypeScriptTree(relDir: string): void {
  if (!fs.existsSync(path.join(ROOT, relDir))) {
    warnings.push(`Directory not found, skipped: ${relDir}/`);
    return;
  }
  for (const rel of walk(relDir).filter((f) => f.endsWith(".ts"))) {
    copyFile(rel, rel);
  }
}

function exportUi(): void {
  const uiDir = path.join(ROOT, "ui");
  if (!fs.existsSync(uiDir)) {
    warnings.push("ui/ not found, UI source skipped");
    return;
  }
  if (fs.existsSync(path.join(uiDir, "src"))) {
    for (const rel of walk("ui/src")) {
      copyFile(rel, rel);
    }
  } else {
    warnings.push("ui/src not found, skipped");
  }
  copyOptional("ui/index.html");
  copyOptional("ui/package.json");
  copyOptional("ui/vite.config.ts");
  for (const name of fs.readdirSync(uiDir)) {
    if (/^tsconfig.*\.json$/.test(name)) {
      copyFile(path.posix.join("ui", name), path.posix.join("ui", name));
    }
  }
}

function writeManifest(): void {
  const lines = [
    "BunkerSettle submission bundle",
    "Generated by scripts/export-submission.ts (npm run submission)",
    "",
    "Note: the .txt files under contracts/ are Solidity sources (.sol) renamed",
    "to .txt for submission. Rename them back to .sol before compiling.",
    "",
    "Exported file -> original path",
    "-------------------------------",
    ...exported.map((f) => `${f.exported} -> ${f.original}`),
    "",
  ];
  fs.writeFileSync(path.join(OUT_DIR, MANIFEST_NAME), lines.join("\n"), "utf8");
}

function formatBytes(bytes: number): string {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

function totalSize(files: string[]): number {
  return files.reduce((sum, f) => sum + fs.statSync(path.join(OUT_DIR, f)).size, 0);
}

function main(): void {
  fs.rmSync(OUT_DIR, { recursive: true, force: true });
  fs.mkdirSync(OUT_DIR, { recursive: true });

  exportContracts();

  for (const rel of ["hardhat.config.ts", "package.json", "tsconfig.json", ".env.example", "SPEC.md", "docs/DECISIONS.md"]) {
    copyRequired(rel);
  }
  copyOptional("README.md");

  exportTypeScriptTree("scripts");
  exportTypeScriptTree("test");
  exportUi();

  writeManifest();

  const files = [...exported.map((f) => f.exported), MANIFEST_NAME];
  for (const warning of warnings) {
    console.warn(`WARNING: ${warning}`);
  }
  console.log(`Submission written to ${OUT_DIR}`);
  console.log(`Files: ${files.length} (${exported.length} exported + ${MANIFEST_NAME})`);
  console.log(`Total size: ${formatBytes(totalSize(files))}`);
}

main();
